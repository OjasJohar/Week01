//03. Create a program to convert the distance of 10.8 kilometers to miles.

import java.lang.*;

class kilometers_To_Miles_03{

	public static void main(String[] args){
                
            // Given kilometers :
	    double kilometers=10.8;
		
	    // Calculating miles from given kilometer :
            double miles= kilometers * 1.6;
		
	    //Printing the miles we get after converting kilometer :
            System.out.print("The distance "+ kilometers +" km in miles is "+ miles);
	}
}	